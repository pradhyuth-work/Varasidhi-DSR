// Team access: read-only logins for buyers and team leads.
//
// Kept apart from the staff login on purpose:
//   * its own tables (portal_accounts, portal_team_buyers) — nothing existing is altered;
//   * its own cookie (dsr_team), scoped to /api/team, signed with a different domain
//     string, so a team session can never be read as an admin/store-manager session
//     and the staff cookie can never be read here;
//   * every /api/team route is mounted BEFORE the staff gate in server.js and answers
//     for itself; it only ever reads (SELECT inside a READ ONLY transaction) and only
//     returns unit counts — no rates, revenue, payments or balances;
//   * the buyers a login may see come from the database on every request, never from
//     the browser.
import crypto from "node:crypto";
import { promisify } from "node:util";
import express from "express";
import { database, pool, withTransaction } from "./database.js";

const scrypt = promisify(crypto.scrypt);

const COOKIE = "dsr_team";
const COOKIE_PATH = "/api/team";
const SESSION_TTL_MS = 12 * 60 * 60 * 1000;
const MAX_FAILS = 5;
const LOCK_MINUTES = 15;
// Passwords: 6-30 visible characters, no spaces, not case-sensitive (stored and checked in lower case).
const PIN_RE = /^[\x21-\x7e]{6,30}$/;
const USERNAME_RE = /^[a-z0-9._-]{3,30}$/;
const MONTH_RE = /^(\d{4})-(0[1-9]|1[0-2])$/;
const isProd = process.env.NODE_ENV === "production";

const IST_DATE = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Kolkata", year: "numeric", month: "2-digit", day: "2-digit",
});
const currentMonth = () => IST_DATE.format(new Date()).slice(0, 7);

// ---------------------------------------------------------------------------
// Tables. Created on first use (idempotent), so deploying needs no manual
// schema step. Foreign keys cascade from profiles, so deleting a buyer in the
// admin screen still works exactly as before.
// ---------------------------------------------------------------------------
const DDL = `
CREATE TABLE IF NOT EXISTS portal_accounts (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind            TEXT NOT NULL CHECK (kind IN ('buyer', 'team_lead')),
  username        TEXT NOT NULL,
  pin_hash        TEXT NOT NULL,
  display_name    TEXT,
  profile_id      INTEGER REFERENCES profiles(id) ON DELETE CASCADE,
  active          BOOLEAN NOT NULL DEFAULT true,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until    timestamptz,
  last_login_at   timestamptz,
  created_by      TEXT,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz,
  CONSTRAINT portal_kind_shape CHECK (
    (kind = 'buyer' AND profile_id IS NOT NULL) OR (kind = 'team_lead' AND profile_id IS NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS portal_accounts_username_uq ON portal_accounts (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS portal_accounts_profile_uq ON portal_accounts (profile_id) WHERE profile_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS portal_team_buyers (
  team_lead_id INTEGER NOT NULL REFERENCES portal_accounts(id) ON DELETE CASCADE,
  profile_id   INTEGER NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  PRIMARY KEY (profile_id)
);
ALTER TABLE portal_accounts   ENABLE ROW LEVEL SECURITY;
ALTER TABLE portal_team_buyers ENABLE ROW LEVEL SECURITY;
`;

let readyPromise = null;
function ready() {
  if (!readyPromise) {
    readyPromise = (async () => {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        await client.query("SELECT pg_advisory_xact_lock(727001)");
        await client.query(DDL);
        await client.query("COMMIT");
      } catch (error) {
        try { await client.query("ROLLBACK"); } catch { /* keep original error */ }
        throw error;
      } finally {
        client.release();
      }
    })().catch((error) => {
      readyPromise = null; // try again on the next request
      throw error;
    });
  }
  return readyPromise;
}

// ---------------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------------
const fail = (res, status, error) => res.status(status).json({ error });

function secret() {
  const s = process.env.SESSION_SECRET;
  if (s) return s;
  return isProd ? null : "dev-insecure-secret-change-in-production";
}

function parseCookies(req) {
  const out = {};
  for (const pair of (req.headers.cookie || "").split(";")) {
    const idx = pair.indexOf("=");
    if (idx === -1) continue;
    try { out[pair.slice(0, idx).trim()] = decodeURIComponent(pair.slice(idx + 1).trim()); } catch { /* skip bad cookie */ }
  }
  return out;
}

const sign = (payload, key) =>
  crypto.createHmac("sha256", key).update(`team-portal-v1.${payload}`).digest("base64url");

function makeToken(accountId, key) {
  const payload = `t.${accountId}.${Date.now() + SESSION_TTL_MS}`;
  return `${payload}.${sign(payload, key)}`;
}

function readToken(token, key) {
  if (!token || !key) return null;
  const parts = token.split(".");
  if (parts.length !== 4 || parts[0] !== "t") return null;
  const payload = parts.slice(0, 3).join(".");
  const a = Buffer.from(parts[3]);
  const b = Buffer.from(sign(payload, key));
  if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) return null;
  if (!(Number(parts[2]) > Date.now())) return null;
  const id = Number(parts[1]);
  return Number.isInteger(id) && id > 0 ? id : null;
}

function cookieAttrs(value, maxAgeSec) {
  const attrs = [`${COOKIE}=${value}`, `Path=${COOKIE_PATH}`, "HttpOnly", "SameSite=Strict", `Max-Age=${maxAgeSec}`];
  if (isProd) attrs.push("Secure");
  return attrs.join("; ");
}

async function hashPin(pin) {
  const salt = crypto.randomBytes(16);
  const N = 16384, r = 8, p = 1;
  const key = await scrypt(pin, salt, 32, { N, r, p });
  return `scrypt$${N}$${r}$${p}$${salt.toString("base64")}$${key.toString("base64")}`;
}

async function checkPin(pin, stored) {
  const parts = String(stored || "").split("$");
  if (parts.length !== 6 || parts[0] !== "scrypt") return false;
  const [, N, r, p, salt, hash] = parts;
  const expected = Buffer.from(hash, "base64");
  const key = await scrypt(pin, Buffer.from(salt, "base64"), expected.length, { N: Number(N), r: Number(r), p: Number(p) });
  return key.length === expected.length && crypto.timingSafeEqual(key, expected);
}

let dummyHash = null; // so an unknown username costs the same time as a wrong PIN
async function burnTime(pin) {
  if (!dummyHash) dummyHash = await hashPin("000000");
  await checkPin(pin, dummyHash);
}

// Best-effort brake per IP. Serverless instances do not share memory, so the
// real protection is the per-account lock in the database.
const ipFails = new Map();
const clientIp = (req) => String(req.headers["x-forwarded-for"] || req.ip || "").split(",")[0].trim();
function ipBlocked(ip) {
  const e = ipFails.get(ip);
  if (!e) return false;
  if (e.reset < Date.now()) { ipFails.delete(ip); return false; }
  return e.n >= 20;
}
function ipFailed(ip) {
  const e = ipFails.get(ip);
  if (!e || e.reset < Date.now()) ipFails.set(ip, { n: 1, reset: Date.now() + 10 * 60 * 1000 });
  else e.n += 1;
  if (ipFails.size > 500) for (const [k, v] of ipFails) if (v.reset < Date.now()) ipFails.delete(k);
}

// Everything read for a team session runs in a READ ONLY transaction, so even a
// future coding mistake here cannot write to the database.
async function readOnly(fn) {
  const client = await pool.connect();
  try {
    await client.query("BEGIN READ ONLY");
    await client.query("SET LOCAL statement_timeout = 8000");
    const out = await fn(client);
    await client.query("COMMIT");
    return out;
  } catch (error) {
    try { await client.query("ROLLBACK"); } catch { /* keep original error */ }
    throw error;
  } finally {
    client.release();
  }
}

