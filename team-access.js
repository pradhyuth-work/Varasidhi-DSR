const asId = (v) => (Number.isInteger(Number(v)) && Number(v) > 0 ? Number(v) : null);

function checkUsername(raw) {
  const u = String(raw || "").trim().toLowerCase();
  return USERNAME_RE.test(u) ? u : null;
}
function checkPinForSetup(pin) {
  const p = String(pin || "").toLowerCase();
  if (!PIN_RE.test(p)) return { error: "Use a password of 6 to 30 characters, no spaces." };
  const staff = [process.env.ADMIN_PASSWORD || "5252", process.env.USER_PASSWORD || ""];
  if (staff.some((x) => x && x.toLowerCase() === p)) return { error: "Choose a password that is different from the staff passwords." };
  return { pin: p };
}
function conflict(error) {
  if (error?.code !== "23505") return null;
  if (String(error.constraint || "").includes("username")) return "That username is already taken.";
  if (String(error.constraint || "").includes("profile")) return "One of those buyers already has a login or is in another team.";
  return "That conflicts with an existing login.";
}

portalAdminRouter.get("/", async (_req, res) => {
  try {
    const profiles = await database.all("SELECT id, name, hidden FROM profiles ORDER BY id");
    const accounts = await database.all(
      "SELECT id, kind, username, display_name, profile_id, active, locked_until, last_login_at FROM portal_accounts ORDER BY id",
    );
    const links = await database.all("SELECT team_lead_id, profile_id FROM portal_team_buyers");
    const buyerLogin = new Map(accounts.filter((a) => a.kind === "buyer").map((a) => [a.profile_id, a]));
    res.json({
      buyers: profiles.map((p) => {
        const a = buyerLogin.get(p.id);
        return {
          profile_id: p.id, name: p.name, hidden: p.hidden,
          login: a ? { id: a.id, username: a.username, active: a.active, last_login_at: a.last_login_at } : null,
        };
      }),
      team_leads: accounts.filter((a) => a.kind === "team_lead").map((a) => ({
        id: a.id, name: a.display_name, username: a.username, active: a.active, last_login_at: a.last_login_at,
        profile_ids: links.filter((l) => l.team_lead_id === a.id).map((l) => l.profile_id),
      })),
    });
  } catch (error) {
    console.error("Failed to list team access", error.message);
    fail(res, 500, "Unable to load team access.");
  }
});

// Create or update the login for one buyer.
portalAdminRouter.put("/buyers/:profileId", async (req, res) => {
  const profileId = asId(req.params.profileId);
  const username = checkUsername(req.body?.username);
  if (!profileId) return fail(res, 400, "Choose a buyer.");
  if (!username) return fail(res, 400, "Username: 3 to 30 characters, letters, numbers, dot, dash or underscore.");
  const wantsPin = req.body?.pin !== undefined && req.body?.pin !== "";
  let hash = null;
  if (wantsPin) {
    const v = checkPinForSetup(req.body.pin);
    if (v.error) return fail(res, 400, v.error);
    hash = await hashPin(v.pin);
  }
  try {
    const profile = await database.get("SELECT id, name FROM profiles WHERE id = ?", [profileId]);
    if (!profile) return fail(res, 404, "Buyer profile not found.");
    const existing = await database.get("SELECT id FROM portal_accounts WHERE kind = 'buyer' AND profile_id = ?", [profileId]);
    if (existing) {
      await database.run(
        `UPDATE portal_accounts
            SET username = ?, pin_hash = COALESCE(?, pin_hash), display_name = ?,
                failed_attempts = 0, locked_until = NULL, updated_at = now()
          WHERE id = ?`,
        [username, hash, profile.name, existing.id],
      );
      return res.json({ id: existing.id, updated: true });
    }
    if (!hash) return fail(res, 400, "Set a PIN for the new login.");
    const created = await database.run(
      `INSERT INTO portal_accounts (kind, username, pin_hash, display_name, profile_id, created_by)
       VALUES ('buyer', ?, ?, ?, ?, 'Admin')`,
      [username, hash, profile.name, profileId],
    );
    res.status(201).json({ id: created.id, updated: false });
  } catch (error) {
    const msg = conflict(error);
    if (msg) return fail(res, 409, msg);
    console.error("Failed to save buyer login", error.message);
    fail(res, 500, "Unable to save the login.");
  }
});

// Assign buyers to a team lead inside an open transaction. A buyer can be in one team only.
async function setTeam(tx, teamLeadId, profileIds) {
  const ids = [...new Set((profileIds || []).map(asId))];
  if (ids.some((v) => v === null)) throw Object.assign(new Error("bad ids"), { status: 400, msg: "Choose valid buyers." });
  if (ids.length) {
    const found = await tx.all("SELECT id FROM profiles WHERE id = ANY(?::int[])", [ids]);
    if (found.length !== ids.length) throw Object.assign(new Error("missing"), { status: 404, msg: "One of those buyers no longer exists." });
    const taken = await tx.all(
      `SELECT pr.name FROM portal_team_buyers tb JOIN profiles pr ON pr.id = tb.profile_id
        WHERE tb.profile_id = ANY(?::int[]) AND tb.team_lead_id <> ?`,
      [ids, teamLeadId],
    );
    if (taken.length) throw Object.assign(new Error("taken"), { status: 409, msg: `Already in another team: ${taken.map((t) => t.name).join(", ")}.` });
  }
  await tx.run("DELETE FROM portal_team_buyers WHERE team_lead_id = ?", [teamLeadId]);
  for (const pid of ids) {
    await tx.run("INSERT INTO portal_team_buyers (team_lead_id, profile_id) VALUES (?, ?) RETURNING team_lead_id", [teamLeadId, pid]);
  }
}
const sendErr = (res, error, label) => {
  if (error?.status) return fail(res, error.status, error.msg);
  const msg = conflict(error);
  if (msg) return fail(res, 409, msg);
  console.error(label, error.message);
  return fail(res, 500, "Unable to save the team lead.");
};

portalAdminRouter.post("/team-leads", async (req, res) => {
  const name = String(req.body?.name || "").trim();
  const username = checkUsername(req.body?.username);
  if (!name || name.length > 120) return fail(res, 400, "Enter the team lead's name.");
  if (!username) return fail(res, 400, "Username: 3 to 30 characters, letters, numbers, dot, dash or underscore.");
  const v = checkPinForSetup(req.body?.pin);
  if (v.error) return fail(res, 400, v.error);
  try {
    const hash = await hashPin(v.pin);
    const id = await withTransaction(async (tx) => {
      const created = await tx.run(
        `INSERT INTO portal_accounts (kind, username, pin_hash, display_name, created_by)
         VALUES ('team_lead', ?, ?, ?, 'Admin')`,
        [username, hash, name],
      );
      await setTeam(tx, created.id, req.body?.profileIds);
      return created.id;
    });
    res.status(201).json({ id });
  } catch (error) {
    sendErr(res, error, "Failed to create team lead");
  }
});

portalAdminRouter.patch("/team-leads/:id", async (req, res) => {
  const id = asId(req.params.id);
  if (!id) return fail(res, 400, "Choose a team lead.");
  const body = req.body || {};
  let name = null, username = null, hash = null;
  if (body.name !== undefined) {
    name = String(body.name).trim();
    if (!name || name.length > 120) return fail(res, 400, "Enter the team lead's name.");
  }
  if (body.username !== undefined) {
    username = checkUsername(body.username);
    if (!username) return fail(res, 400, "Username: 3 to 30 characters, letters, numbers, dot, dash or underscore.");
  }
  if (body.pin !== undefined && body.pin !== "") {
    const v = checkPinForSetup(body.pin);
    if (v.error) return fail(res, 400, v.error);
    hash = await hashPin(v.pin);
  }
  try {
    await withTransaction(async (tx) => {
      const acct = await tx.get("SELECT id FROM portal_accounts WHERE id = ? AND kind = 'team_lead'", [id]);
      if (!acct) throw Object.assign(new Error("none"), { status: 404, msg: "Team lead not found." });
      await tx.run(
        `UPDATE portal_accounts
            SET display_name = COALESCE(?, display_name), username = COALESCE(?, username),
                pin_hash = COALESCE(?, pin_hash),
                failed_attempts = CASE WHEN ? THEN 0 ELSE failed_attempts END,
                locked_until    = CASE WHEN ? THEN NULL ELSE locked_until END,
                updated_at = now()
          WHERE id = ?`,
        [name, username, hash, hash !== null, hash !== null, id],
      );
      if (Array.isArray(body.profileIds)) await setTeam(tx, id, body.profileIds);
    });
    res.json({ ok: true });
  } catch (error) {
    sendErr(res, error, "Failed to update team lead");
  }
});

