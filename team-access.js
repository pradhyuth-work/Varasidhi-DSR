portalAdminRouter.delete("/:id", async (req, res) => {
  const id = asId(req.params.id);
  if (!id) return fail(res, 400, "Choose a login.");
  try {
    const r = await database.run("DELETE FROM portal_accounts WHERE id = ?", [id]);
    if (!r.changes) return fail(res, 404, "Login not found.");
    res.json({ ok: true });
  } catch (error) {
    console.error("Failed to remove login", error.message);
    fail(res, 500, "Unable to remove the login.");
  }
});
