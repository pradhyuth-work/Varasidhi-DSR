teamRouter.post("/login", async (req, res) => {
  const key = secret();
  if (!key) return fail(res, 503, "Team sign-in is not available right now.");
  const username = String(req.body?.username || "").trim().toLowerCase();
  const pin = String(req.body?.pin || "").toLowerCase();
  const ip = clientIp(req);
  if (ipBlocked(ip)) return fail(res, 429, "Too many attempts. Try again in a few minutes.");
  if (!USERNAME_RE.test(username) || !PIN_RE.test(pin)) {
    await burnTime(pin);
    ipFailed(ip);
    return fail(res, 401, "Incorrect username or password.");
  }
  try {
    await ready();
    const acct = await database.get(
      `SELECT id, kind, display_name, pin_hash, active, locked_until,
              (locked_until IS NOT NULL AND locked_until > now()) AS locked
         FROM portal_accounts WHERE lower(username) = ?`,
      [username],
    );
    if (!acct) {
      await burnTime(pin);
      ipFailed(ip);
      return fail(res, 401, "Incorrect username or password.");
    }
    if (acct.locked) return fail(res, 429, "Too many attempts. Try again in a few minutes.");
    const ok = await checkPin(pin, acct.pin_hash);
    if (!ok) {
      await database.run(
        `UPDATE portal_accounts
            SET failed_attempts = CASE WHEN failed_attempts + 1 >= ${MAX_FAILS} THEN 0 ELSE failed_attempts + 1 END,
                locked_until    = CASE WHEN failed_attempts + 1 >= ${MAX_FAILS} THEN now() + interval '${LOCK_MINUTES} minutes' ELSE locked_until END
          WHERE id = ?`,
        [acct.id],
      );
      ipFailed(ip);
      return fail(res, 401, "Incorrect username or password.");
    }
    if (!acct.active) return fail(res, 403, "This login is switched off. Ask the admin.");
    await database.run(
      "UPDATE portal_accounts SET failed_attempts = 0, locked_until = NULL, last_login_at = now() WHERE id = ?",
      [acct.id],
    );
    res.setHeader("Set-Cookie", cookieAttrs(makeToken(acct.id, key), Math.floor(SESSION_TTL_MS / 1000)));
    res.json({ kind: acct.kind, name: acct.display_name });
  } catch (error) {
    console.error("Team login failed", error.message);
    fail(res, 503, "Team sign-in is not available right now.");
  }
});

teamRouter.post("/logout", (_req, res) => {
  res.setHeader("Set-Cookie", cookieAttrs("", 0));
  res.json({ ok: true });
});

// Every route below needs a valid team session whose account is still active.
async function requireAccount(req, res, next) {
  try {
    const id = readToken(parseCookies(req)[COOKIE], secret());
    if (!id) return fail(res, 401, "Please sign in.");
    await ready();
    const acct = await database.get(
      "SELECT id, kind, display_name, profile_id, active FROM portal_accounts WHERE id = ?",
      [id],
    );
    if (!acct || !acct.active) {
      res.setHeader("Set-Cookie", cookieAttrs("", 0));
      return fail(res, 401, "Please sign in.");
    }
    req.acct = acct;
    next();
  } catch (error) {
    console.error("Team session check failed", error.message);
    fail(res, 503, "Team access is not available right now.");
  }
}

teamRouter.get("/me", requireAccount, (req, res) => {
  res.json({ kind: req.acct.kind, name: req.acct.display_name });
});

teamRouter.get("/performance", requireAccount, async (req, res) => {
  try {
    const now = currentMonth();
    let month = MONTH_RE.test(String(req.query?.month || "")) ? String(req.query.month) : now;
    if (month > now) month = now;
    if (month < "2020-01") month = "2020-01";
    const [y, m] = month.split("-").map(Number);
    const from = `${month}-01`;
    const to = m === 12 ? `${y + 1}-01-01` : `${y}-${String(m + 1).padStart(2, "0")}-01`;

    const data = await readOnly(async (c) => {
      // Which buyers this login may see — decided here, never by the browser.
      const scope = req.acct.kind === "buyer"
        ? (await c.query("SELECT id FROM profiles WHERE id = $1", [req.acct.profile_id])).rows
        : (await c.query(
            `SELECT pr.id FROM portal_team_buyers tb JOIN profiles pr ON pr.id = tb.profile_id
              WHERE tb.team_lead_id = $1`,
            [req.acct.id],
          )).rows;
      const ids = scope.map((r) => r.id);
      if (!ids.length) return { buyers: [], rows: [] };
      const buyers = (await c.query("SELECT id, name FROM profiles WHERE id = ANY($1::int[]) ORDER BY name, id", [ids])).rows;
      // Units only: no unit price, no line totals, no payments, no balances.
      const rows = (await c.query(
        `SELECT s.buyer_id, p.id AS product_id, p.name AS product_name, SUM(i.qty_sold)::int AS units
           FROM dsr_items i
           JOIN dsr_sessions s ON s.id = i.dsr_id
           JOIN products p     ON p.id = i.product_id
          WHERE s.status = 'SETTLED' AND s.date >= $1 AND s.date < $2
            AND s.buyer_id = ANY($3::int[]) AND i.qty_sold > 0
          GROUP BY s.buyer_id, p.id, p.name
          ORDER BY s.buyer_id, units DESC, p.id`,
        [from, to, ids],
      )).rows;
      return { buyers, rows };
    });

    const byBuyer = new Map(data.buyers.map((b) => [b.id, { name: b.name, units: 0, products: [] }]));
    const team = new Map();
    let total = 0;
    for (const r of data.rows) {
      const b = byBuyer.get(r.buyer_id);
      if (!b) continue;
      b.units += r.units;
      b.products.push({ name: r.product_name, units: r.units });
      total += r.units;
      const t = team.get(r.product_id) || { name: r.product_name, units: 0 };
      t.units += r.units;
      team.set(r.product_id, t);
    }
    res.json({
      month,
      kind: req.acct.kind,
      name: req.acct.display_name,
      total_units: total,
      products: [...team.values()].sort((a, b) => b.units - a.units),
      buyers: [...byBuyer.values()],
    });
  } catch (error) {
    console.error("Team performance failed", error.message);
    fail(res, 500, "Unable to load performance right now.");
  }
});

